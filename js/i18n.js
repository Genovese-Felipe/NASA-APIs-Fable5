let currentLang = 'en';

export function getLang() { return currentLang; }

export function setLang(code) {
  if (STRINGS[code]) currentLang = code;
  return currentLang;
}

export function detectLang() {
  const saved = typeof localStorage !== 'undefined' && localStorage.getItem('cosmoscope.lang');
  if (saved && STRINGS[saved]) return saved;
  const navList = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language])) || [];
  for (const tag of navList) {
    if (!tag) continue;
    const base = tag.toLowerCase().split('-')[0];
    if (STRINGS[base]) return base;
  }
  return 'en';
}

export function t(key, vars) {
  let s = STRINGS[currentLang][key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
  }
  return s;
}
